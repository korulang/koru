#!/usr/bin/env python3
# gen.py — emit input.k for the linalg engine race.
#
# Rounds k=0..K-1 nest inside each other's `| exact` arms (Koru arm bodies
# are scopes — a value bound inside an arm cannot leave it). Each round
# dup-cascades the matrix custody a_k into the copies each consumer needs,
# races bareiss `solve` vs `solve-dixon` on A_k x = A_k * 1, then squares
# into a_{k+1}. det(A_k) = det(A0)^(2^k): minor width doubles per round.
#
# K=10 segfaults the compiler backend (measured 2026-11-26, rational-kit
# ac997e7ea — deep arm nesting, not a runtime fault). K=9 is the wall.
K = 9

def ind(d):
    return "    " * d

lines = []

lines.append("""// linalg engine race — same custody, same system, two exact engines:
//   bareiss — solve(A,b): denom-clear, fraction-free elimination, Rat
//             back-substitution. Cost tracks intermediate-minor width.
//   dixon   — solve-dixon(A,b,p): mod-p inverse, Hensel lift one digit
//             per step, Wang recon, full-Q residual witness. Cost is
//             flat while x has small denominators (recon hits early);
//             its residual check still pays coefficient width.
// The system: A_k = A0^(2^k), b = A_k * ones — so x = ones exactly.
// det(A_k) = det(A0)^(2^k): minor width doubles every round.
// Generated by gen.py — do not hand-edit.
import std/io
import std/time
import std/linalg

std/linalg:lit(s: "5x5: 23 11 7 13 17 19 41 29 31 37 43 47 53 59 61 67 71 73 79 83 89 97 101 103 107")
| exact a0 |> std/linalg:lit(s: "5x1: 1 1 1 1 1")
    | exact o0 |> std/linalg:dup(m: a0): dq0""")

# `|>` chain steps + union arms share col 4d; arm bodies nest at d+1.
# Phantom law: every live <mat!> obligation must be discharged on EVERY
# union arm — non-exact arms free the copies still live at that point.
def rest(k, d, first_done):
    last = (k == K - 1)
    L = lines
    if not first_done:
        L.append(f"{ind(d)}|> std/linalg:dup(m: a{k}): dq{k}")
    if not last:
        L.append(f"{ind(d)}|> std/linalg:dup(m: dq{k}.a): dqa{k}")
        L.append(f"{ind(d)}|> std/linalg:dup(m: dqa{k}.a): dqaa{k}")
        L.append(f"{ind(d)}|> std/linalg:dup(m: dq{k}.b): dqbb{k}")
        c_bmat, c_solve, c_dixon, c_sql, c_sqr = (
            f"dqaa{k}.a", f"dqaa{k}.b", f"dqa{k}.b", f"dqbb{k}.a", f"dqbb{k}.b")
        live_after_dups = [f"dqaa{k}.b", f"dqa{k}.b", f"dqbb{k}.a", f"dqbb{k}.b"]
    else:
        L.append(f"{ind(d)}|> std/linalg:dup(m: dq{k}.a): dqa{k}")
        c_bmat, c_solve, c_dixon = f"dqa{k}.a", f"dqa{k}.b", f"dq{k}.b"
        live_after_dups = [f"dqa{k}.b", f"dq{k}.b"]
    src_o = "o0" if k == 0 else f"do{k-1}.b"
    L.append(f"{ind(d)}|> std/linalg:dup(m: {src_o}): do{k}")
    L.append(f"{ind(d)}|> std/linalg:mul({c_bmat}, b: do{k}.a)")

    def frees(names):
        return "".join(f" |> std/linalg:free(m: {n})" for n in names)

    L.append(f"{ind(d)}| exact b{k} |> std/linalg:dup(m: b{k}): db{k}")
    L.append(f"{ind(d+1)}|> std/time:now(): tb{k}")
    L.append(f"{ind(d+1)}|> std/linalg:solve(a: {c_solve}, b: db{k}.a)")
    L.append(f"{ind(d+1)}| exact x |> std/linalg:render(m: x): xt |> std/io:print.ln(\"k={k} bareiss x={{{{ xt:s }}}}\") |> std/io:free(content: xt)")
    solve_fail_live = [c_dixon, f"db{k}.b", f"do{k}.b"] + ([c_sql, c_sqr] if not last else [])
    L.append(f"{ind(d+1)}| singular |> std/io:print.ln(\"k={k} bareiss singular\")" + frees(solve_fail_live))
    L.append(f"{ind(d+1)}| bad-dims |> std/io:print.ln(\"k={k} bareiss bad-dims\")" + frees(solve_fail_live))
    L.append(f"{ind(d+1)}|> std/time:elapsed(start: tb{k}): eb{k}")
    L.append(f"{ind(d+1)}|> std/time:now(): td{k}")
    L.append(f"{ind(d+1)}|> std/linalg:solve-dixon(a: {c_dixon}, db{k}.b, prime: 999983)")
    L.append(f"{ind(d+1)}| exact x |> std/linalg:render(m: x): xu |> std/io:print.ln(\"k={k} dixon   x={{{{ xu:s }}}}\") |> std/io:free(content: xu)")
    dixon_fail_live = [f"do{k}.b"] + ([c_sql, c_sqr] if not last else [])
    for arm in ["singular", "bad-dims", "bad-prime", "open"]:
        L.append(f"{ind(d+1)}| {arm} |> std/io:print.ln(\"k={k} dixon   {arm}\")" + frees(dixon_fail_live))
    L.append(f"{ind(d+1)}|> std/time:elapsed(start: td{k}): ed{k}")
    L.append(f"{ind(d+1)}|> std/io:print.ln(\"k={k} bareiss ms={{{{ eb{k}.ms:f }}}} dixon ms={{{{ ed{k}.ms:f }}}}\")")
    if not last:
        L.append(f"{ind(d+1)}|> std/linalg:mul({c_sql}, {c_sqr})")
        L.append(f"{ind(d+1)}| exact a{k+1} |> std/linalg:dup(m: a{k+1}): dq{k+1}")
        rest(k + 1, d + 2, True)
        L.append(f"{ind(d+1)}| dims |> std/io:print.ln(\"k={k} square dims\")" + frees([f"do{k}.b"]))
    else:
        L.append(f"{ind(d+1)}|> std/linalg:free(m: do{k}.b)")
        L.append(f"{ind(d+1)}|> std/io:print.ln(\"done\")")
    bmat_dims_live = live_after_dups + [f"do{k}.b"]
    L.append(f"{ind(d)}| dims |> std/io:print.ln(\"k={k} b dims\")" + frees(bmat_dims_live))

rest(0, 2, True)
lines.append("    | bad uy |> std/io:print.ln(\"bad-lit\") |> std/linalg:free(m: a0)")
lines.append("| bad ux |> std/io:print.ln(\"bad-lit\")")

import sys
out = sys.argv[1] if len(sys.argv) > 1 else "input.k"
open(out, "w").write("\n".join(lines) + "\n")
print(f"generated {out} (K={K})")
